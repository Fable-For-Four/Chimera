import re

MD_SPECIAL = re.compile(r"([\\`*_\[\]<>|#])")


def md(text):
    flat = " ".join(str(text).split())
    return MD_SPECIAL.sub(r"\\\1", flat)


def cites(ids):
    return ", ".join(f"`{md(i)}`" for i in ids)


def data_line(case, source):
    events = f"{case['summary']['events']:,} events"
    if source and source.get("kind") == "upload":
        unread = source.get("unparsed", 0)
        extra = f", {unread:,} lines could not be read" if unread else ""
        return f"{events} from the uploaded file {md(source['name'])}{extra}"
    return f"{events} from {case['summary']['sources']} simulated log sources"


def header(case, source, exported_at):
    verdict = case["verdict"]
    lines = [
        f"# Incident report: {md(verdict['label'])}",
        "",
        f"> {md(verdict['headline'])}",
        "",
        f"- **Confidence:** {verdict['confidence']}%",
        f"- **Data:** {data_line(case, source)}",
    ]
    if case.get("level"):
        lines.append(
            f"- **Stress test:** {case['level']}% of logs deleted ({case['deleted']:,} events)"
        )
    lines.append(f"- **Exported:** {exported_at}")
    return lines


def what_happened(case):
    lines = ["", "## What happened", ""]
    if not case["report"]:
        return [*lines, "No attack chain was found, so there is nothing to report as an attack."]
    return [*lines, *(f"- {md(item['text'])} ({cites(item['cites'])})" for item in case["report"])]


def timeline(case):
    if not case["chain"]:
        return []
    lines = [
        "",
        "## Timeline",
        "",
        "| Step | Time (UTC) | Stage | What happened | ATT&CK technique | Sure | Evidence |",
        "|---|---|---|---|---|---|---|",
    ]
    for step in case["chain"]:
        what = md(step["what"]) + (" (inferred, its log is missing)" if step["inferred"] else "")
        evidence = cites(e["id"] for e in step["exhibits"] if e.get("present", True)) or "none"
        lines.append(
            f"| {step['step']} | {step['time']} | {md(step['stage'])} | {what} | "
            f"{md(step['technique'])} | {step['confidence']}% | {evidence} |"
        )
    return lines


def limits(case):
    if not case["limits"]:
        return []
    return ["", "## What the logs cannot prove", "", *(f"- {md(item)}" for item in case["limits"])]


def actions(case, approvals):
    if not case["actions"]:
        return []
    lines = ["", "## Response actions", ""]
    for action in case["actions"]:
        approval = approvals.get(action["id"])
        text = f"{md(action['kind'])}: {md(action['text'])}"
        if approval:
            by = md(approval["approved_by"] or "a deleted user")
            lines.append(f"- [x] {text}, approved by {by} at {approval['approved_at']}")
        else:
            lines.append(f"- [ ] {text}, waiting for approval")
    return lines


def build(case, approvals, source, exported_at):
    lines = [
        *header(case, source, exported_at),
        *what_happened(case),
        *timeline(case),
        *limits(case),
        *actions(case, approvals),
        "",
        "---",
        "",
        "Generated by Chimera. Every claim cites the log lines it rests on.",
    ]
    return "\n".join(lines) + "\n"
